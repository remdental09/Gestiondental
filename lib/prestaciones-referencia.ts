/** Rango orientativo: entre el 60% y el 110% del valor referencial (los precios de clínicas suelen quedar bajo el arancel de isapre), redondeado a cifras cómodas de cobrar. */
export const RANGE_LOW = 0.6;
export const RANGE_HIGH = 1.1;

function roundPrice(value: number): number {
  const step = value < 50_000 ? 500 : value < 500_000 ? 1_000 : 5_000;
  return Math.max(step, Math.round(value / step) * step);
}

/** {low, high} sugeridos para una prestación, o null si la fuente no trae valor. */
export function suggestedRange(code: string): { low: number; high: number; reference: number } | null {
  const reference = REFERENCE_PRICES[code];
  if (!reference) return null;
  return { low: roundPrice(reference * RANGE_LOW), high: roundPrice(reference * RANGE_HIGH), reference };
}
