/** Código propio: «9» + grupo (2 dígitos, como en 5011000 → 11) + correlativo de 4 dígitos dentro del grupo. */
export function complementCodes(): Array<[string, string, number]> {
  const counters = new Map<number, number>();
  return COMPLEMENT_ROWS.map(([group, name]) => {
    const n = (counters.get(group) ?? 0) + 1;
    counters.set(group, n);
    return [`9${String(group + 1).padStart(2, "0")}${String(n).padStart(4, "0")}`, name, group];
  });
}

export const isComplementCode = (code: string) => code.startsWith("9");
